import test from 'node:test';
import assert from 'node:assert/strict';
import unit1 from '../content/vocabulary/units/unit-01.js';
import { buildActivity } from '../src/vocabulary/activity-builder.js';
import { availableActivityTypesForTarget, buildTargetPracticeQuestion } from '../src/vocabulary/session-targets.js';
import { activitiesForMode } from '../src/vocabulary/activity-catalogue.js';

function targetFor(vocabularyId) {
  const target = unit1.occurrences.find(row => row.vocabularyId === vocabularyId);
  const item = unit1.items.find(row => row.vocabularyId === vocabularyId);
  assert.ok(target, `missing occurrence for ${vocabularyId}`);
  assert.ok(item, `missing item for ${vocabularyId}`);
  return { target, item };
}

function contextsFor(target) {
  return unit1.contexts.filter(row => row.occurrenceId === target.occurrenceId);
}

function content() {
  return {
    ...unit1,
    itemsById:Object.fromEntries(unit1.items.map(row => [row.vocabularyId, row])),
    contextsByOccurrence:Object.fromEntries(unit1.occurrences.map(row => [row.occurrenceId, contextsFor(row)]))
  };
}

function sourceKind(question) {
  if (unit1.contexts.some(row => row.contextId === question.contentId)) return 'context';
  if (unit1.activities.some(row => row.activityContentId === question.contentId)) return 'unit_activity';
  return null;
}

test('Word Family Switch fails closed when a target has word-family metadata but no curated writing task', () => {
  const { target, item } = targetFor('vocab_avoid');
  assert.ok(item.wordFamily?.length > 0, 'control target should have word-family metadata');
  assert.equal(unit1.activities.some(row => row.contentType === 'writing_set' && row.activityData?.taskType === 'word_family' && row.activityData?.linkedVocabularyIds?.includes(item.vocabularyId)), false);
  assert.throws(() => buildActivity({
    activityType:'word_family_switch',
    occurrence:target,
    item,
    contexts:contextsFor(target),
    unitActivities:unit1.activities,
    unitItems:unit1.items,
    unitContexts:unit1.contexts,
    unitOccurrences:unit1.occurrences,
    mastery:{ status:'building' },
    readinessStage:'building',
    seed:'word-family-authoritative-source'
  }), /No curated word-family content is available for this target/);
});

test('eligibility never advertises generic word-family metadata as a live Word Family Switch', () => {
  const { target, item } = targetFor('vocab_avoid');
  const available = availableActivityTypesForTarget({ content:content(), target, item, contexts:contextsFor(target) });
  assert.equal(available.includes('word_family_switch'), false);
});

test('every activity generated by every live Unit 1 practice mode resolves to an authoritative context or unit activity', () => {
  const data = content();
  const stages = ['new','building','secure','mastered'];
  for (const mode of ['learn','context','question_text','phrase_paraphrase','idea_paraphrase','writing','adaptive']) {
    assert.ok(activitiesForMode(mode).length > 0, `${mode} must have live activities`);
    for (const stage of stages) {
      for (const target of unit1.occurrences) {
        try {
          const built = buildTargetPracticeQuestion({
            content:data,
            target,
            mastery:{ status:stage, strandEvidence:{ meaning:9, recognition:9, context:9, paraphrasing:9, production:9 }, recentErrorCount:0 },
            practiceMode:mode,
            recentActivities:[],
            supportState:null,
            reviewDue:false,
            usedContentIds:[],
            seed:`authoritative-source:${mode}:${stage}:${target.occurrenceId}`
          });
          assert.ok(sourceKind(built.question), `${mode}/${stage}/${target.vocabularyId}/${built.question.type} produced non-authoritative contentId ${built.question.contentId}`);
        } catch (error) {
          if (String(error?.message ?? '').includes('No suitable curated activity')) continue;
          if (String(error?.message ?? '').includes('No eligible')) continue;
          // Targets legitimately unavailable for this stage/mode are allowed; questions that do build are checked above.
        }
      }
    }
  }
});
