// Job 9 (Part 9/18): the Unit 1 database sync is DERIVED from the canonical JavaScript release - never hand-edited.
// `node scripts/generate-unit1-sync-sql.mjs`          prints the status
// `node scripts/generate-unit1-sync-sql.mjs --write`  rewrites docs/vocabulary-content-updates/job9-unit-01-sync-chunk-N.sql
// Upserts only (insert ... on conflict do update); nothing is deleted. Toby runs the chunks in order in the Supabase SQL editor BEFORE the
// Edge Function is redeployed, because the Edge Function reads sense.masteryPassages / wordFamilyForms / masteryContexts from vocabulary_items.
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';

const RELEASE = new URL('../content/vocabulary/releases/unit-01.js', import.meta.url);
export const outFile = n => new URL(`../docs/vocabulary-content-updates/job9-unit-01-sync-chunk-${n}.sql`, import.meta.url);
export function generatedChunks() {
  const run = spawnSync(process.execPath, [new URL('./export-vocabulary-sql.mjs', import.meta.url).pathname, RELEASE.pathname], { encoding: 'utf8', maxBuffer: 1 << 28 });
  if (run.status !== 0) throw new Error(run.stderr || 'export failed');
  const chunks = [...run.stdout.matchAll(/---BEGIN VOCAB SQL CHUNK (\d+)---\n([\s\S]*?)\n---END VOCAB SQL CHUNK \1---/g)].map(m => ({ number: Number(m[1]), sql: m[2] }));
  const total = chunks.length;
  return chunks.map(({ number, sql }) => ({ number, text: `-- Unit 1 content sync (Job 9), part ${number} of ${total}. GENERATED by scripts/generate-unit1-sync-sql.mjs from content/vocabulary/releases/unit-01.js - do not edit.\n-- Upserts only (insert ... on conflict do update); nothing is deleted. Run parts 1..${total} in order, BEFORE redeploying the Edge Function.\n${sql}\n` }));
}
if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file://').href) {
  const chunks = generatedChunks();
  if (process.argv.includes('--write')) for (const { number, text } of chunks) fs.writeFileSync(outFile(number), text);
  console.log(`${chunks.length} chunks${process.argv.includes('--write') ? ' written' : ''}: ${chunks.map(c => c.text.length).join(', ')} bytes`);
}
