// Job 9 (Part 9/18): the Unit 1 database sync is DERIVED from the canonical JavaScript release - never hand-edited.
// `node scripts/generate-unit1-sync-sql.mjs`          prints the status
// `node scripts/generate-unit1-sync-sql.mjs --write`  rewrites docs/vocabulary-content-updates/job9-unit-01-sync-chunk-N.sql
// Upserts only (insert ... on conflict do update); nothing is deleted. Toby runs the chunks in order in the Supabase SQL editor BEFORE the
// Edge Function is redeployed, because the Edge Function reads sense.masteryPassages / wordFamilyForms / masteryContexts from vocabulary_items.
import fs from 'node:fs';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { releaseFileFor, releaseNumbers, syncChunkNameFor, padUnit } from './vocabulary-releases.mjs';

// Also generates any other released unit: `--unit N` or `--all` (units that have a releases/unit-NN.js). Unit 1 (the default) is unchanged.
export const outFile = (n, unitNumber = 1) => new URL(`../docs/vocabulary-content-updates/${syncChunkNameFor(unitNumber, n)}`, import.meta.url);
const headerFor = (unitNumber, number, total) => Number(unitNumber) === 1
  ? `-- Unit 1 content sync (Job 9), part ${number} of ${total}. GENERATED by scripts/generate-unit1-sync-sql.mjs from content/vocabulary/releases/unit-01.js - do not edit.`
  : `-- Unit ${unitNumber} content sync, part ${number} of ${total}. GENERATED by scripts/generate-unit1-sync-sql.mjs --unit ${unitNumber} from content/vocabulary/releases/unit-${padUnit(unitNumber)}.js - do not edit.`;
export function generatedChunks(unitNumber = 1, releasesDir) {
  const release = pathToFileURL(releaseFileFor(unitNumber, releasesDir));
  const run = spawnSync(process.execPath, [new URL('./export-vocabulary-sql.mjs', import.meta.url).pathname, release.pathname], { encoding: 'utf8', maxBuffer: 1 << 28 });
  if (run.status !== 0) throw new Error(run.stderr || 'export failed');
  const chunks = [...run.stdout.matchAll(/---BEGIN VOCAB SQL CHUNK (\d+)---\n([\s\S]*?)\n---END VOCAB SQL CHUNK \1---/g)].map(m => ({ number: Number(m[1]), sql: m[2] }));
  const total = chunks.length;
  return chunks.map(({ number, sql }) => ({ number, text: `${headerFor(unitNumber, number, total)}\n-- Upserts only (insert ... on conflict do update); nothing is deleted. Run parts 1..${total} in order, BEFORE redeploying the Edge Function.\n${sql}\n` }));
}
if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file://').href) {
  const flag = process.argv.indexOf('--unit');
  const units = process.argv.includes('--all') ? releaseNumbers() : [flag > 0 ? Number(process.argv[flag + 1]) : 1];
  for (const unitNumber of units) {
    const chunks = generatedChunks(unitNumber);
    if (process.argv.includes('--write')) for (const { number, text } of chunks) fs.writeFileSync(outFile(number, unitNumber), text);
    console.log(`unit ${unitNumber}: ${chunks.length} chunks${process.argv.includes('--write') ? ' written' : ''}: ${chunks.map(c => c.text.length).join(', ')} bytes`);
  }
}
