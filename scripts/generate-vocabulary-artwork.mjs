// Run with pinned sharp@0.34.5 available to Node (e.g. through NODE_PATH).
// Original PNGs are read-only. Derivatives use lossless WebP after resizing.
import {createRequire} from 'node:module';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {SHIPPED_PNG} from '../src/vocabulary/graphics-manifest.js';
const sharp=createRequire(import.meta.url)('sharp');
const root=new URL('../',import.meta.url),delivery={};
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
for(const file of SHIPPED_PNG){
 const input=await readFile(new URL('assets/vocabulary/'+file,root));
 const meta=await sharp(input).metadata();
 const variants=[];
 for(const width of (file.startsWith('units/')?[640,960]:[512])){
  const {data,info}=await sharp(input).resize({width,withoutEnlargement:true}).webp({lossless:true,effort:6}).toBuffer({resolveWithObject:true});
  const src='assets/vocabulary/delivery/'+file.replace('.png','.'+hash(data).slice(0,12)+'.webp');
  await mkdir(new URL(src.substring(0,src.lastIndexOf('/')+1),root),{recursive:true});
  await writeFile(new URL(src,root),data);variants.push({src,width:info.width});
  console.log(file,width,input.length,'->',data.length);
 }
 delivery[file]={variants,originalWidth:meta.width,sourceHash:hash(input)};
}
await writeFile(new URL('src/vocabulary/graphics-delivery.js',root),'// Generated by scripts/generate-vocabulary-artwork.mjs; originals stay unchanged.\nexport const GRAPHIC_DELIVERY = Object.freeze('+JSON.stringify(delivery,null,2)+');\n');
